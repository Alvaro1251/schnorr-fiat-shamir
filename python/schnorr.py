"""Interactive Schnorr identification in a small, *insecure* teaching group.

The multiplicative subgroup generated by G has prime order Q in Z_P*.  These
small public parameters make the arithmetic easy to inspect; they offer no
real-world security against discrete-log attacks.
"""

from __future__ import annotations

import secrets

P = 2039
Q = 1019
G = 4


def _scalar(value: int, *, nonzero: bool = False) -> bool:
    return type(value) is int and (1 if nonzero else 0) <= value < Q


def _group_element(value: int) -> bool:
    return type(value) is int and 1 <= value < P and pow(value, Q, P) == 1


def public_key(secret: int) -> int:
    """Return Y = G**secret mod P for a nonzero secret in Z_Q."""
    if not _scalar(secret, nonzero=True):
        raise ValueError("secret must be in 1..Q-1")
    return pow(G, secret, P)


def generate_keypair() -> tuple[int, int]:
    """Return (secret, public key), sampling the secret with a CSPRNG."""
    secret = secrets.randbelow(Q - 1) + 1
    return secret, public_key(secret)


class SchnorrProver:
    """Prover for the three-move commitment/challenge/response protocol.

    ``nonce`` is an optional deterministic test hook. Never reuse it with a
    real secret outside the nonce-reuse demonstration.
    """

    def __init__(self, secret: int, *, nonce: int | None = None) -> None:
        self.public_key = public_key(secret)
        if nonce is not None and not _scalar(nonce, nonzero=True):
            raise ValueError("nonce must be in 1..Q-1")
        self._secret = secret
        self._fixed_nonce = nonce
        self._active_nonce: int | None = None

    def commit(self) -> int:
        """Send R = G**k. Starting another round discards the prior nonce."""
        self._active_nonce = (
            self._fixed_nonce
            if self._fixed_nonce is not None
            else secrets.randbelow(Q - 1) + 1
        )
        return pow(G, self._active_nonce, P)

    def respond(self, challenge: int) -> int:
        """Return s = k + c*x mod Q for an issued challenge."""
        if self._active_nonce is None:
            raise RuntimeError("commit before responding")
        if not _scalar(challenge):
            raise ValueError("challenge must be in 0..Q-1")
        response = (self._active_nonce + challenge * self._secret) % Q
        self._active_nonce = None
        return response


class SchnorrVerifier:
    """Verifier holding the public key and checking g**s = R*Y**c."""

    def __init__(self, public_key_value: int) -> None:
        if not _group_element(public_key_value) or public_key_value == 1:
            raise ValueError("public key must be a nonidentity subgroup element")
        self.public_key = public_key_value

    @staticmethod
    def challenge() -> int:
        return secrets.randbelow(Q)

    def verify(self, commitment: int, challenge: int, response: int) -> bool:
        if not (_group_element(commitment) and _scalar(challenge) and _scalar(response)):
            return False
        return pow(G, response, P) == commitment * pow(self.public_key, challenge, P) % P
